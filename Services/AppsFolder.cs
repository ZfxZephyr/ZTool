using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Xml.Linq;
using Avalonia.Media.Imaging;

namespace ZTool.Services;

/// <summary>
/// The shell's AppsFolder: every app Windows will launch by AppUserModelID,
/// including the Store builds that never drop a .lnk into the Start Menu.
/// Those entries are addressed by AUMID rather than by path, so each one
/// carries both the name a person says and the id the shell wants.
/// </summary>
public static class AppsFolder
{
    /// <summary>What the shell knows about one launchable app.</summary>
    public sealed record Entry(string Name, string Id, string Publisher, Bitmap? Icon);

    // Shell plumbing that is always running and never worth a row of its own.
    // Matched on the package family name, which holds still across Windows
    // builds in a way the display name does not. 「设置」 deliberately stays out:
    // it is an app people search for.
    private static readonly string[] ShellComponents =
    {
        "Microsoft.Windows.ShellExperienceHost",
        "Microsoft.Windows.StartMenuExperienceHost",
        "Microsoft.Windows.Search",
        "Microsoft.Windows.Cortana",
        "Microsoft.Windows.CloudExperienceHost",
        "Microsoft.Windows.CapturePicker",
        "Microsoft.Windows.ContentDeliveryManager",
        "Microsoft.Windows.NarratorQuickStart",
        "Microsoft.Windows.ParentalControls",
        "Microsoft.Windows.PeopleExperienceHost",
        "Microsoft.Windows.PinningConfirmationDialog",
        "Microsoft.Windows.XGpuEjectDialog",
        "Microsoft.Windows.Apprep.ChxApp",
        "Microsoft.Windows.CallingShellApp",
        "Microsoft.Windows.OOBENetworkCaptivePortal",
        "Microsoft.Windows.OOBENetworkConnectionFlow",
        "Microsoft.AAD.BrokerPlugin",
        "Microsoft.AccountsControl",
        "Microsoft.BioEnrollment",
        "Microsoft.CredDialogHost",
        "Microsoft.ECApp",
        "Microsoft.LockApp",
        "Microsoft.PPIProjection",
        "Microsoft.AsyncTextService",
        "Microsoft.XboxGameCallableUI",
        "Microsoft.UI.Xaml",
        "Microsoft.NET.Native",
        "Microsoft.Services.Store.Engagement",
        "Windows.PrintDialog",
    };

    /// <summary>Moniker the shell resolves for any entry in this folder.</summary>
    public static string Moniker(string id) => $@"shell:AppsFolder\{id}";

    /// <summary>True when the id is a package-qualified AUMID rather than a path.</summary>
    public static bool IsAppId(string id) => id.Contains('!');

    public static bool IsShellComponent(string id) =>
        ShellComponents.Any(c => id.StartsWith(c, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// How much an id is the app's own identity. A package AUMID is what the
    /// publisher registered; a shell-generated one is only a stand-in for a
    /// shortcut, so it loses to anything real when both claim a name.
    /// </summary>
    private static int Standing(string id) =>
        IsAppId(id) ? 0
        : id.StartsWith("Microsoft.AutoGenerated", StringComparison.OrdinalIgnoreCase) ? 2
        : 1;

    /// <summary>
    /// Docs and web links arrive in this folder too. They are the Start Menu's
    /// readme pile, and a launcher is for things that run.
    /// </summary>
    private static readonly string[] DocumentExtensions =
    {
        ".url", ".html", ".htm", ".chm", ".pdf",
    };

    /// <summary>
    /// Everything the AppsFolder will launch. Failures return what has been
    /// gathered so far — a launcher with no Store apps is still a launcher.
    /// </summary>
    public static IReadOnlyList<Entry> Enumerate()
    {
        var found = new Dictionary<string, Entry>(StringComparer.OrdinalIgnoreCase);

        object? shell = null;
        object? folder = null;
        object? items = null;

        try
        {
            var shellType = Type.GetTypeFromProgID("Shell.Application");
            if (shellType is null)
            {
                return Array.Empty<Entry>();
            }

            shell = Activator.CreateInstance(shellType);
            if (shell is null)
            {
                return Array.Empty<Entry>();
            }

            folder = shellType.InvokeMember("NameSpace", BindingFlags.InvokeMethod, null, shell, new object?[] { "shell:AppsFolder" });
            if (folder is null)
            {
                return Array.Empty<Entry>();
            }

            var folderType = folder.GetType();
            items = folderType.InvokeMember("Items", BindingFlags.InvokeMethod, null, folder, null);
            if (items is null)
            {
                return Array.Empty<Entry>();
            }

            var itemType = items.GetType();
            var count = Convert.ToInt32(itemType.InvokeMember("Count", BindingFlags.GetProperty, null, items, null));

            for (var i = 0; i < count; i++)
            {
                object? item = null;

                try
                {
                    item = itemType.InvokeMember("Item", BindingFlags.InvokeMethod, null, items, new object[] { i });
                    if (item is null)
                    {
                        continue;
                    }

                    var entry = Read(item);
                    if (entry is null)
                    {
                        continue;
                    }

                    // Same display name, two ids: keep the one that is really
                    // the app. First one in wins only against an equal standing.
                    if (!found.TryGetValue(entry.Name, out var held) || Standing(entry.Id) < Standing(held.Id))
                    {
                        found[entry.Name] = entry;
                    }
                }
                catch (Exception ex) when (ex is COMException or ExternalException or TargetInvocationException or ArgumentException)
                {
                    // One unreadable row is not worth losing the rest.
                }
                finally
                {
                    if (item is not null)
                    {
                        Marshal.FinalReleaseComObject(item);
                    }
                }
            }
        }
        catch (Exception ex) when (ex is COMException or ExternalException or TargetInvocationException or InvalidCastException)
        {
            return found.Values.ToList();
        }
        finally
        {
            if (items is not null)
            {
                Marshal.FinalReleaseComObject(items);
            }

            if (folder is not null)
            {
                Marshal.FinalReleaseComObject(folder);
            }

            if (shell is not null)
            {
                Marshal.FinalReleaseComObject(shell);
            }
        }

        return found.Values.ToList();
    }

    /// <summary>
    /// How to hand this entry back to the shell. A plain path speaks for itself;
    /// everything else — a known-folder path, an AUMID, a shell-generated id —
    /// is only addressable through the folder it came from.
    /// </summary>
    public static string ParsingName(string id) => File.Exists(id) ? id : Moniker(id);

    private static Entry? Read(object item)
    {
        var name = (GetProperty(item, "Name") as string)?.Trim();
        var id = (GetProperty(item, "Path") as string)?.Trim();

        if (string.IsNullOrEmpty(name) || string.IsNullOrEmpty(id))
        {
            return null;
        }

        if (IsShellComponent(id) || DocumentExtensions.Any(ext => id.EndsWith(ext, StringComparison.OrdinalIgnoreCase)))
        {
            return null;
        }

        return new Entry(name, id, Publisher(item, id), ShellIcon.For(ParsingName(id)));
    }

    private static string Publisher(object item, string id)
    {
        if (IsAppId(id))
        {
            var installPath = (Call(item, "ExtendedProperty", "System.AppUserModel.PackageInstallPath") as string)?.Trim();
            var publisher = string.IsNullOrEmpty(installPath) ? string.Empty : FromManifest(installPath);
            return Resolved(publisher);
        }

        return Resolved((Call(item, "ExtendedProperty", "System.CompanyName") as string)?.Trim() ?? string.Empty);
    }

    /// <summary>
    /// Some packages never resolve their resource strings and hand back the
    /// placeholder itself. That is not a name to show anyone.
    /// </summary>
    private static string Resolved(string value) =>
        value.StartsWith("ms-resource:", StringComparison.OrdinalIgnoreCase) ? string.Empty : value;

    /// <summary>
    /// The package's own claim about who published it. Prefers the display name;
    /// the certificate subject is the fallback and reads fine once the CN= is
    /// stripped off.
    /// </summary>
    private static string FromManifest(string installPath)
    {
        try
        {
            var manifest = Path.Combine(installPath, "AppxManifest.xml");
            if (!File.Exists(manifest))
            {
                return string.Empty;
            }

            var document = XDocument.Load(manifest);
            var ns = document.Root?.Name.Namespace;

            if (ns is null)
            {
                return string.Empty;
            }

            var displayName = document.Root?
                .Element(ns + "Properties")?
                .Element(ns + "PublisherDisplayName")?
                .Value;

            if (!string.IsNullOrWhiteSpace(displayName))
            {
                return displayName.Trim();
            }

            var subject = document.Root?.Element(ns + "Identity")?.Attribute("Publisher")?.Value;
            return string.IsNullOrWhiteSpace(subject) ? string.Empty : CompanyFromSubject(subject);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Xml.XmlException)
        {
            return string.Empty;
        }
    }

    private static string CompanyFromSubject(string subject)
    {
        var company = subject.Trim();
        if (company.StartsWith("CN=", StringComparison.OrdinalIgnoreCase))
        {
            company = company[3..];
        }

        // "CN=Microsoft Corporation, O=…" — stop at the first comma.
        var comma = company.IndexOf(',');
        return (comma > 0 ? company[..comma] : company).Trim();
    }

    private static object? GetProperty(object item, string name) => Invoke(item, name, BindingFlags.GetProperty, null);

    private static object? Call(object item, string name, string argument) => Invoke(item, name, BindingFlags.InvokeMethod, new object[] { argument });

    private static object? Invoke(object item, string name, BindingFlags flags, object?[]? arguments)
    {
        try
        {
            return item.GetType().InvokeMember(name, flags, null, item, arguments);
        }
        catch (Exception ex) when (ex is COMException or ExternalException or TargetInvocationException)
        {
            return null;
        }
    }
}
